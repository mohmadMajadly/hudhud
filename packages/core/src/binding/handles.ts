// ---- public types ------------------------------------------------------------------

/**
 * One block of user input (plan §2.2).
 *
 * @public
 */
export type UserContentBlock =
  | { readonly type: 'text'; readonly text: string }
  | {
      readonly type: 'image';
      readonly mediaType: 'image/png' | 'image/jpeg' | 'image/gif' | 'image/webp';
      readonly dataBase64: string;
    };

/**
 * What the application sends to the harness: text, or content blocks.
 *
 * @public
 */
export type UserInput = string | { readonly content: readonly UserContentBlock[] };

/**
 * What a live session knows about itself (plan §2.2).
 *
 * @public
 */
export interface SessionInfo {
  readonly id: string;
  readonly mode: 'create' | 'resume' | 'fork';
  readonly forkedFrom?: string;
  /** The spawned pid (process identity). */
  readonly pid: number;
  /** The pid the harness reports for itself (informational). */
  readonly cliPid?: number;
  readonly version: string;
  readonly apiKeySource?: string;
  /** The harness's token source, informational (K10). */
  readonly tokenSource?: string;
  readonly features: readonly string[];
  /** What this session got (K2). */
  readonly containment: ProcessContainment;
}

/**
 * One turn: awaitable through `done`, iterable for its own events,
 * interruptible.
 *
 * @public
 */
export interface Turn extends AsyncIterable<HudhudEvent> {
  /** The turn id: a fresh UUID generated by hudhud. */
  readonly id: string;
  /**
   * Resolves with the result of the turn, error results included (K21);
   * rejects only for session-level failures. Never waits on a subscriber.
   */
  readonly done: Promise<TurnResult>;
  /** Interrupts the turn (gated until it started, ADR-0008). */
  interrupt(opts?: { readonly cancelQueued?: boolean }): Promise<void>;
}

/**
 * A harness session (plan §2.2).
 *
 * @public
 */
export interface Session extends AsyncDisposable {
  readonly id: string;
  readonly info: SessionInfo;
  /** Resolves once the session ended and its process tree was cleaned up. Never rejects. */
  readonly closed: Promise<void>;
  /** Sends `prompt` and resolves with the turn's result (K21). */
  ask(prompt: UserInput, opts?: { readonly signal?: AbortSignal }): Promise<TurnResult>;
  /** Sends `input` and returns the turn. */
  send(
    input: UserInput,
    opts?: { readonly signal?: AbortSignal; readonly events?: SubscriberOptions },
  ): Turn;
  /** The session-wide event stream; starts with the replayed `compat` event (K20). */
  events(opts?: SubscriberOptions): AsyncIterable<HudhudEvent>;
  /** Changes the harness's permission mode. */
  setPermissionMode(mode: string, opts?: { readonly signal?: AbortSignal }): Promise<void>;
  /** Drains and ends the session under one deadline from the call (K13). */
  close(opts?: { readonly signal?: AbortSignal }): Promise<void>;
}

/**
 * A connected harness (plan §2.2). Disposing it disposes its sessions.
 *
 * @public
 */
export interface Harness extends AsyncDisposable {
  readonly capabilities: HarnessCapabilities;
  readonly binary: BinaryInfo;
  readonly compat: CompatInfo;
  readonly securityPosture: SecurityPosture;
}

/**
 * The harness binary a {@link Harness} runs (plan §2.2).
 *
 * @public
 */
export interface BinaryInfo {
  readonly path: string;
  readonly requestedPath?: string;
  /** From the connect probe (K4). */
  readonly version: string;
  readonly source: 'option' | 'native-install' | 'path';
  readonly verification: BinaryVerification;
}

// ---- the driver seam ---------------------------------------------------------------------

/**
 * A turn as the driver hands it to the handle.
 *
 * @beta
 */
export interface TurnCore {
  readonly id: string;
  readonly done: Promise<TurnResult>;
  /** The turn's events; present when the send asked for them. */
  readonly events: AsyncIterableIterator<HudhudEvent, undefined, undefined> | undefined;
}

/**
 * What the handles need from the session driver.
 *
 * @beta
 */
export interface SessionCore {
  readonly id: string;
  /** Available once the handshake succeeded. */
  readonly info: SessionInfo;
  readonly closed: Promise<void>;
  /**
   * Starts a turn. With `iterate`, its events are buffered from now on;
   * `signal` ends that buffer with `AbortError`.
   */
  sendTurn(
    input: UserInput,
    options: {
      readonly iterate: boolean;
      readonly events?: SubscriberOptions | undefined;
      readonly signal?: AbortSignal | undefined;
    },
  ): TurnCore;
  interrupt(turnId: string | undefined, cancelQueued: boolean): Promise<void>;
  setPermissionMode(mode: string): Promise<void>;
  subscribe(
    options: SubscriberOptions | undefined,
  ): AsyncIterableIterator<HudhudEvent, undefined, undefined>;
  close(): Promise<void>;
  abort(intent: 'abort' | 'dispose'): Promise<void>;
}

// ---- input validation ----------------------------------------------------------------------

const MEDIA_TYPES: ReadonlySet<string> = new Set([
  'image/png',
  'image/jpeg',
  'image/gif',
  'image/webp',
]);

function invalidInput(rule: string): InvalidOptionsError {
  return new InvalidOptionsError(
    'User input must be a string or { content } with text and base64 image blocks.',
    { details: { path: 'input', rule } },
  );
}

function blockOf(item: JsonValue): UserContentBlock {
  if (typeof item !== 'object' || item === null || Array.isArray(item)) {
    throw invalidInput('content-block');
  }
  const value = item as JsonObject;
  const keys = Object.keys(value).sort().join(',');
  const type = value['type'];
  const text = value['text'];
  if (type === 'text' && typeof text === 'string' && keys === 'text,type') {
    return { type: 'text', text };
  }
  const mediaType = value['mediaType'];
  const data = value['dataBase64'];
  if (
    type === 'image' &&
    typeof mediaType === 'string' &&
    MEDIA_TYPES.has(mediaType) &&
    typeof data === 'string' &&
    keys === 'dataBase64,mediaType,type'
  ) {
    return {
      type: 'image',
      mediaType: mediaType as Extract<UserContentBlock, { type: 'image' }>['mediaType'],
      dataBase64: data,
    };
  }
  throw invalidInput('content-block');
}

/**
 * Checks user input strictly and returns a fresh copy (the application
 * cannot change it after the call).
 *
 * @throws {@link InvalidOptionsError} (`details.rule`) for anything else
 * @beta
 */
export function normalizeUserInput(input: unknown): UserInput {
  if (typeof input === 'string') return input;
  const copy = copyJson(input);
  if (typeof copy !== 'object' || copy === null || Array.isArray(copy)) {
    throw invalidInput('user-input');
  }
  const object = copy as JsonObject;
  const content = object['content'];
  if (Object.keys(object).length !== 1 || !Array.isArray(content)) {
    throw invalidInput('user-input');
  }
  return { content: (content as readonly JsonValue[]).map((block) => blockOf(block)) };
}

// ---- handles -------------------------------------------------------------------------------------

/** Marks a promise as handled without changing it (no unhandled-rejection report). */
function handled<T>(promise: Promise<T>): Promise<T> {
  promise.catch(() => undefined);
  return promise;
}

/** A thrown value as an `Error` (an adapter hook may throw anything). */
function asError(value: unknown): Error {
  return value instanceof Error
    ? value
    : new Error('user input could not be encoded', { cause: value });
}

function abortedBy(signal: AbortSignal): AbortError {
  return AbortError.fromSignal(signal);
}

/**
 * Settles with `promise`, or rejects with `AbortError` as soon as `signal`
 * aborts (then `onAbort` runs once). The listener is removed either way.
 * Callers handle a signal that is already aborted themselves.
 */
function withSignal<T>(
  promise: Promise<T>,
  signal: AbortSignal | undefined,
  onAbort: () => void = () => undefined,
): Promise<T> {
  if (signal === undefined) return promise;
  return new Promise<T>((resolve, reject) => {
    const listener = (): void => {
      onAbort();
      reject(abortedBy(signal));
    };
    signal.addEventListener('abort', listener, { once: true });
    promise.then(
      (value) => {
        signal.removeEventListener('abort', listener);
        resolve(value);
      },
      (error: unknown) => {
        signal.removeEventListener('abort', listener);
        // eslint-disable-next-line @typescript-eslint/prefer-promise-reject-errors -- forwards the driver's error unchanged
        reject(error);
      },
    );
  });
}

class TurnHandle implements Turn {
  readonly id: string;
  readonly done: Promise<TurnResult>;
  readonly #core: SessionCore;
  readonly #events: AsyncIterableIterator<HudhudEvent, undefined, undefined> | undefined;

  constructor(core: SessionCore, turn: TurnCore) {
    this.#core = core;
    this.id = turn.id;
    this.done = handled(turn.done);
    this.#events = turn.events;
  }

  interrupt(opts: { readonly cancelQueued?: boolean } = {}): Promise<void> {
    return this.#core.interrupt(this.id, opts.cancelQueued === true);
  }

  [Symbol.asyncIterator](): AsyncIterator<HudhudEvent> {
    if (this.#events === undefined) throw new Error('this turn has no event iterator');
    return this.#events;
  }
}

class SessionHandle implements Session {
  readonly #core: SessionCore;

  constructor(core: SessionCore) {
    this.#core = core;
  }

  get id(): string {
    return this.#core.id;
  }

  get info(): SessionInfo {
    return this.#core.info;
  }

  get closed(): Promise<void> {
    return this.#core.closed;
  }

  ask(prompt: UserInput, opts: { readonly signal?: AbortSignal } = {}): Promise<TurnResult> {
    const { signal } = opts;
    if (signal?.aborted === true) return Promise.reject(abortedBy(signal));
    let turn: TurnCore;
    try {
      turn = this.#core.sendTurn(prompt, { iterate: false });
    } catch (error) {
      return Promise.reject(asError(error));
    }
    return withSignal(handled(turn.done), signal, () => {
      // Gated by the machine; its own outcome does not matter to ask().
      this.#core.interrupt(turn.id, false).catch(() => undefined);
    });
  }

  send(
    input: UserInput,
    opts: { readonly signal?: AbortSignal; readonly events?: SubscriberOptions } = {},
  ): Turn {
    const { signal } = opts;
    const turn = this.#core.sendTurn(input, { iterate: true, events: opts.events, signal });
    if (signal !== undefined) {
      const interrupt = (): void => {
        this.#core.interrupt(turn.id, false).catch(() => undefined);
      };
      if (signal.aborted) interrupt();
      else {
        signal.addEventListener('abort', interrupt, { once: true });
        void turn.done.then(
          () => {
            signal.removeEventListener('abort', interrupt);
          },
          () => {
            signal.removeEventListener('abort', interrupt);
          },
        );
      }
    }
    return new TurnHandle(this.#core, turn);
  }

  events(opts?: SubscriberOptions): AsyncIterable<HudhudEvent> {
    return this.#core.subscribe(opts);
  }

  setPermissionMode(mode: string, opts: { readonly signal?: AbortSignal } = {}): Promise<void> {
    const { signal } = opts;
    if (signal?.aborted === true) return Promise.reject(abortedBy(signal));
    return withSignal(handled(this.#core.setPermissionMode(mode)), signal);
  }

  close(opts: { readonly signal?: AbortSignal } = {}): Promise<void> {
    const { signal } = opts;
    if (signal?.aborted === true) {
      void handled(this.#core.abort('abort'));
      return Promise.reject(abortedBy(signal));
    }
    return withSignal(this.#core.close(), signal, () => {
      void handled(this.#core.abort('abort'));
    });
  }

  [Symbol.asyncDispose](): Promise<void> {
    return this.#core.abort('dispose');
  }
}

/**
 * The public {@link Session} over a driver.
 *
 * @beta
 */
export function createSession(core: SessionCore): Session {
  return new SessionHandle(core);
}

/**
 * What a {@link Harness} knows at connect.
 *
 * @beta
 */
export interface HarnessFacts {
  readonly capabilities: HarnessCapabilities;
  readonly binary: BinaryInfo;
  readonly compat: CompatInfo;
  readonly securityPosture: SecurityPosture;
}

/**
 * A {@link Harness} that tracks its live sessions: disposing it disposes
 * them (plan §2.2) and refuses new ones with `HARNESS_DISPOSED`. Adapters
 * build their harness handle on it.
 *
 * @beta
 */
export class HarnessBase implements Harness {
  readonly capabilities: HarnessCapabilities;
  readonly binary: BinaryInfo;
  readonly compat: CompatInfo;
  readonly securityPosture: SecurityPosture;
  readonly #sessions = new Set<Session>();
  #disposed: Promise<void> | undefined;

  constructor(facts: HarnessFacts) {
    this.capabilities = facts.capabilities;
    this.binary = facts.binary;
    this.compat = facts.compat;
    this.securityPosture = facts.securityPosture;
  }

  /** Live sessions. */
  get sessionCount(): number {
    return this.#sessions.size;
  }

  /** Whether dispose started. */
  get disposed(): boolean {
    return this.#disposed !== undefined;
  }

  /**
   * Throws `HARNESS_DISPOSED` once dispose started; call before creating a
   * session.
   */
  assertOpen(): void {
    if (this.#disposed !== undefined) {
      throw new HarnessDisposedError('The harness was disposed.');
    }
  }

  /**
   * Tracks a session until it closed. A session tracked after dispose
   * started is disposed at once.
   */
  track(session: Session): void {
    if (this.#disposed !== undefined) {
      void Promise.resolve(session[Symbol.asyncDispose]()).catch(() => undefined);
      return;
    }
    this.#sessions.add(session);
    void session.closed.then(() => {
      this.#sessions.delete(session);
    });
  }

  [Symbol.asyncDispose](): Promise<void> {
    this.#disposed ??= Promise.all(
      [...this.#sessions].map((session) =>
        Promise.resolve(session[Symbol.asyncDispose]()).catch(() => undefined),
      ),
    ).then(() => undefined);
    return this.#disposed;
  }
}
