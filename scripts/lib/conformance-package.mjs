// The data package @hudhudjs/conformance (ADR-0004 amendment of 2026-10-18):
// the expected event streams of the Claude Code conformance suite
// (packages/claude-code/conformance/<scenario>/<platform>[.<case>].expect.jsonl),
// copied byte for byte into packages/conformance/dist/streams/ by every build,
// and a typed index (dist/index.js, dist/index.d.ts) rendered here. Nothing of
// it is committed, so it cannot drift from the fixtures the suite asserts;
// scripts/test/conformance-package.test.ts and `pnpm check:tarball`
// (`checkConformanceTarball`) compare the built and the packed files with the
// sources. Pure functions; the effects are in scripts/conformance-package.mjs.

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The package name. */
export const CONFORMANCE_PACKAGE = '@hudhudjs/conformance';

/** The canonical fixtures, repository-relative. */
export const SOURCE_DIR = 'packages/claude-code/conformance';

/** The package directory, repository-relative. */
export const PACKAGE_DIR = 'packages/conformance';

/** Where the streams lie inside the package. */
export const STREAMS_DIR = 'dist/streams';

/** An expected stream file of the suite: `<platform>[.<case>].expect.jsonl`. */
const STREAM_FILE = /^(linux|win32)(?:\.([a-z0-9][a-z0-9-]*))?\.expect\.jsonl$/u;

/** A scenario directory name. */
const SCENARIO = /^[a-z0-9][a-z0-9-]*$/u;

/**
 * @typedef {object} ConformanceStream
 * @property {string} scenario
 * @property {'linux' | 'win32'} platform
 * @property {string | null} case
 * @property {string} path Relative to the package root.
 * @property {string} specifier The package subpath that resolves it.
 */

/**
 * The streams the package ships, from the files of the fixture directory:
 * every `<scenario>/<platform>[.<case>].expect.jsonl`, sorted by path. Raw
 * transcripts (`*.jsonl`, `*.jsonl.gz`) and the manifest are left out.
 *
 * @param {readonly string[]} files Paths relative to {@link SOURCE_DIR}, with `/`.
 * @returns {{ streams: ConformanceStream[], problems: string[] }}
 */
export function streamsOf(files) {
  /** @type {ConformanceStream[]} */
  const streams = [];
  /** @type {string[]} */
  const problems = [];
  for (const file of [...files].sort()) {
    const parts = file.split('/');
    const name = file.slice(file.lastIndexOf('/') + 1);
    if (!name.endsWith('.expect.jsonl')) continue;
    const [scenario = ''] = parts;
    const match = STREAM_FILE.exec(name);
    if (parts.length !== 2 || !SCENARIO.test(scenario) || match === null) {
      problems.push(`${SOURCE_DIR}/${file}: not <scenario>/<platform>[.<case>].expect.jsonl`);
      continue;
    }
    const platform = /** @type {'linux' | 'win32'} */ (match[1]);
    const path = `${STREAMS_DIR}/${scenario}/${name}`;
    streams.push({
      scenario,
      platform,
      case: match[2] ?? null,
      path,
      specifier: `${CONFORMANCE_PACKAGE}/streams/${scenario}/${name}`,
    });
  }
  if (streams.length === 0 && problems.length === 0) {
    problems.push(`${SOURCE_DIR} holds no expected stream`);
  }
  return { streams, problems };
}

/**
 * The index module, exactly as built.
 *
 * @param {string} version The package's version: the hudhud release.
 * @param {readonly ConformanceStream[]} streams
 * @returns {string}
 */
export function renderIndexJs(version, streams) {
  const entries = streams
    .map(
      (stream) =>
        `  Object.freeze(${JSON.stringify({
          scenario: stream.scenario,
          platform: stream.platform,
          case: stream.case,
          path: stream.path,
          specifier: stream.specifier,
        })}),\n`,
    )
    .join('');
  return [
    `// Generated by scripts/conformance-package.mjs from ${SOURCE_DIR}; do not edit.`,
    `export const HUDHUD_VERSION = ${JSON.stringify(version)};`,
    `export const CONFORMANCE_STREAMS = Object.freeze([\n${entries}]);`,
    '',
  ].join('\n');
}

/** The declarations of the index module, exactly as built. */
export const INDEX_DTS = `/**
 * The expected event streams of hudhud's Claude Code conformance suite, as
 * data. Each file is byte-identical to the stream the conformance suite of
 * this exact hudhud version asserts; pin this package at the same version as
 * \`@hudhudjs/claude-code\`. No shape is promised across versions.
 *
 * @packageDocumentation
 */

/**
 * One expected event stream: a scenario of the conformance suite on one
 * platform.
 *
 * @public
 */
export interface ConformanceStream {
  /** The scenario, for example \`text-turn\`. */
  readonly scenario: string;
  /** The platform the scenario was recorded on. */
  readonly platform: 'linux' | 'win32';
  /** The case within the scenario, or null for its main stream. */
  readonly case: string | null;
  /** The file, relative to the package root. */
  readonly path: string;
  /** The package subpath that resolves the file. */
  readonly specifier: string;
}

/**
 * The hudhud version whose conformance suite asserts exactly these streams.
 *
 * @public
 */
export declare const HUDHUD_VERSION: string;

/**
 * Every expected event stream of this version, sorted by path.
 *
 * @public
 */
export declare const CONFORMANCE_STREAMS: readonly ConformanceStream[];
`;

/**
 * Every file the build writes under the package's `dist/`, by path relative
 * to the package root, with its exact content.
 *
 * @param {string} version
 * @param {readonly ConformanceStream[]} streams
 * @param {(stream: ConformanceStream) => Uint8Array} source The bytes of a stream's source file.
 * @returns {Map<string, Uint8Array>}
 */
export function expectedFiles(version, streams, source) {
  /** @type {Map<string, Uint8Array>} */
  const files = new Map();
  files.set('dist/index.js', Buffer.from(renderIndexJs(version, streams)));
  files.set('dist/index.d.ts', Buffer.from(INDEX_DTS));
  for (const stream of streams) files.set(stream.path, source(stream));
  return files;
}

/**
 * The expected `dist/` files of the package for a version, read from the
 * fixture directory of a repository.
 *
 * @param {string} root The repository root.
 * @param {string} version
 * @returns {{ files: Map<string, Uint8Array>, streams: ConformanceStream[], problems: string[] }}
 */
export function loadExpected(root, version) {
  const base = join(root, SOURCE_DIR);
  const listed = readdirSync(base, { recursive: true, encoding: 'utf8' }).map((file) =>
    file.replaceAll('\\', '/'),
  );
  const { streams, problems } = streamsOf(listed);
  const files = expectedFiles(version, streams, (stream) =>
    readFileSync(join(base, stream.scenario, stream.path.slice(stream.path.lastIndexOf('/') + 1))),
  );
  return { files, streams, problems };
}

/**
 * Compares the files a package holds under `dist/` with the expected ones,
 * both ways: every expected file present with the same bytes, no other file.
 *
 * @param {ReadonlyMap<string, Uint8Array>} expected
 * @param {readonly { path: string, data: Uint8Array }[]} actual Files under `dist/`.
 * @returns {string[]} problems
 */
export function compareFiles(expected, actual) {
  /** @type {string[]} */
  const problems = [];
  const seen = new Set();
  for (const { path, data } of actual) {
    seen.add(path);
    const want = expected.get(path);
    if (want === undefined) {
      problems.push(`${path}: not a file of the conformance data`);
    } else if (!Buffer.from(data).equals(Buffer.from(want))) {
      problems.push(`${path}: differs from its source (${SOURCE_DIR} or the generated index)`);
    }
  }
  for (const path of expected.keys()) {
    if (!seen.has(path)) problems.push(`${path}: missing`);
  }
  return problems;
}
