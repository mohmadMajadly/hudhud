/**
 * The harness-neutral handles `Session`, `Turn` and `Harness` (plan §2.2,
 * ADR-0003, ADR-0007, ADR-0008).
 *
 * @remarks
 * The handles are thin: every decision about the session lives in the
 * driver (`driver.ts`), which implements {@link SessionCore}. The handles add
 * the public API's argument checks and its `AbortSignal` semantics:
 *
 * - `ask()` resolves with the `TurnResult` of every completed turn, error
 *   results included, and rejects only for session-level failures (K21). An
 *   aborted signal interrupts the turn and rejects at once with `AbortError`;
 *   the turn still settles in the background.
 * - `send()` returns a {@link Turn} whose iterator buffers the turn's events
 *   from creation with the subscriber defaults (bounded, `'error'` scoped to
 *   that iterator). An aborted signal interrupts the turn and ends its
 *   iterator with `AbortError`.
 * - `close()` drains (K13); an aborted signal turns the drain into an abort
 *   and rejects with `AbortError`. `Symbol.asyncDispose` aborts.
 * - `setPermissionMode()` rejects at once with `AbortError` when its signal
 *   aborts; the harness's answer is then ignored.
 *
 * Neither `ask()` nor `turn.done` ever waits on a subscriber (ADR-0007).
 *
 * @packageDocumentation
 */

